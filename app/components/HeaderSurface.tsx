import { Platform, StyleSheet, View } from "react-native";
import { BRAND } from "../lib/header";

/**
 * Подложка шапки — своя, потому что у чужой нет тени там, где мы смотрим.
 *
 * Настройка `headerShadowVisible` у навигатора выглядит как одна вещь, а на
 * деле означает три разных: на Android это `elevation: 4` и настоящая тень; на
 * iOS — полоска толщиной в волос; а в браузере вообще НЕ ТЕНЬ, а нижняя
 * граница цветом темы. На бирюзовой шапке такая граница неразличима, поэтому в
 * браузере включать было нечего — что и обнаружилось сразу, как только на неё
 * посмотрели.
 *
 * Здесь тень задаётся явно и на каждой платформе своим средством. Стиль тени
 * нельзя передать через `headerStyle`: навигатор вырезает оттуда `boxShadow`,
 * `elevation` и `shadow*` и в разработке ругается на них. А подложку он отдаёт
 * целиком — это и есть предусмотренное место для такого.
 *
 * Цвет остаётся один и тот же в обоих состояниях: меняется только то, лежит
 * шапка НАД содержимым или заподлицо с ним.
 */
export function HeaderSurface({ lifted }: { lifted: boolean }) {
  return (
    <View
      style={[
        StyleSheet.absoluteFill,
        { backgroundColor: BRAND },
        lifted ? shadow : null,
      ]}
    />
  );
}

/**
 * Мягкая и низкая. Тень под шапкой должна читаться как слой, а не как рамка:
 * заметная настолько, чтобы список под ней «уходил вглубь», и не настолько,
 * чтобы её разглядывали.
 */
const shadow = Platform.select({
  android: { elevation: 6 },
  ios: {
    shadowColor: "#000",
    shadowOpacity: 0.18,
    shadowRadius: 6,
    shadowOffset: { width: 0, height: 3 },
  },
  // Разобранный вид, а не строка: так это значение стиля, а не текст —
  // проверка зашитых надписей справедливо не умеет отличать одно от другого.
  default: {
    boxShadow: [
      { offsetX: 0, offsetY: 3, blurRadius: 8, color: "rgba(0,0,0,0.18)" },
    ],
  },
});
