import * as Haptics from "expo-haptics";
import { Platform } from "react-native";

/**
 * Ответ на прикосновение — короткий толчок, когда изменение действительно
 * сохранено.
 *
 * `expo-haptics` лежал в сборке и не вызывался НИ РАЗУ — нашлось при разборе
 * зависимостей. Это редкий случай: возможность уже оплачена местом в APK, а
 * пользы от неё не было.
 *
 * Одно место, а не двести три. Мутаций в приложении больше двухсот, и
 * расставлять отклик по каждой значило бы забыть половину и потом годами
 * находить забытые — ровно так уже было с обновлением сводок и с проверкой
 * прав. Обработчик у MutationCache знает про КАЖДОЕ удавшееся сохранение и про
 * каждый отказ, поэтому правило живёт там.
 *
 * Сила выбрана самая слабая из существующих. Отклик должен подтверждать, а не
 * требовать внимания: человек отмечает присутствие на встрече, а не играет.
 * Отказ отзывается иначе — не сильнее, а ДРУГИМ рисунком, потому что рука
 * узнаёт разницу раньше, чем глаз находит красную строку.
 *
 * На вебе не делает ничего: `expo-haptics` там пустышка, но лишний вызов на
 * каждое сохранение ни к чему.
 */
export function tapSaved(): void {
  if (Platform.OS === "web") return;
  void Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
}

export function tapRefused(): void {
  if (Platform.OS === "web") return;
  void Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning);
}
